def green_size(E):
    confinement_energy = E - Eg

    a = np.sqrt(
        (3 * np.pi**2 * hbar**2 / 2)
        * (1/me + 1/mh)
        / confinement_energy
    )

    return a * 1e9  # Convert to nm


