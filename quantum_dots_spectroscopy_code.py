from scipy.constants import h, c, hbar, m_e, elementary_charge

Eg = 1.74 * elementary_charge
me = 0.13 * m_e
mh = 0.45 * m_e

def photon_energy(wavelength_nm):
    return h * c / (wavelength_nm * 1e-9)

def calculate_size(wavelength_nm, factor):
    E = photon_energy(wavelength_nm)
    delta_E = E - Eg

    if delta_E <= 0:
        return np.nan

    size = np.sqrt(
        (factor * np.pi**2 * hbar**2 / (2 * delta_E))
        * (1/me + 1/mh)
    )

    return size * 1e9

# Green dots: cube
