"""Quantum Dots: Green and Orange"""

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy.constants import hbar, c, m_e, elementary_charge

# --------------------------------
# 1. Constants
# --------------------------------

Eg = 1.74 * elementary_charge  # CdSe band gap (J)

me = 0.13 * m_e                # Effective electron mass
mh = 0.45 * m_e                # Effective hole mass

# --------------------------------
# 2. Import spectra
# --------------------------------

# Set the separator to ';' and the decimal marker to ','
green = pd.read_csv('/green_em.csv', sep=';', decimal=',')
orange = pd.read_csv('/orange_em.csv', sep=';', decimal=',')

# Check the column names in your CSV files
print("Green columns:", green.columns)
print("Orange columns:", orange.columns)

# Change these if your CSV uses different column names
wavelength_green = green["Wavelength (nm)"].to_numpy()
intensity_green = green["Intensity Source #5"].to_numpy()

wavelength_orange = orange["Wavelength (nm)"].to_numpy()
intensity_orange = orange["Intensity Source #6"].to_numpy()

# --------------------------------
# 3. Find emission peaks
# --------------------------------

# Drop NaN values to avoid Argmax errors if any rows are empty
valid_green = ~np.isnan(wavelength_green) & ~np.isnan(intensity_green)
valid_orange = ~np.isnan(wavelength_orange) & ~np.isnan(intensity_orange)

green_peak = wavelength_green[valid_green][np.argmax(intensity_green[valid_green])]
orange_peak = wavelength_orange[valid_orange][np.argmax(intensity_orange[valid_orange])]

print("Green peak:", green_peak, "nm")
print("Orange peak:", orange_peak, "nm")

# --------------------------------
# 4. Convert wavelength to energy
# --------------------------------

def photon_energy(wavelength):
    wavelength_m = wavelength * 1e-9
    energy = hbar * 2 * np.pi * c / wavelength_m
    return energy

E_green = photon_energy(green_peak)
E_orange = photon_energy(orange_peak)

print("Green photon energy:", E_green / elementary_charge, "eV")
print("Orange photon energy:", E_orange / elementary_charge, "eV")

# --------------------------------
# 5. Calculate quantum dot sizes
# --------------------------------

def green_size(E):
    confinement_energy = E - Eg

    a = np.sqrt(
        (3 * np.pi**2 * hbar**2 / 2)
        * (1/me + 1/mh)
        / confinement_energy
    )

    return a * 1e9  # Convert to nm


def orange_size(E):
    confinement_energy = E - Eg

    b = np.sqrt(
        (2.2 * np.pi**2 * hbar**2 / 2)
        * (1/me + 1/mh)
        / confinement_energy
    )

    return b * 1e9  # Convert to nm


a = green_size(E_green)
b = orange_size(E_orange)

